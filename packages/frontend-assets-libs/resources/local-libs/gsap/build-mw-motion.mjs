#!/usr/bin/env node
/*
 * Builds the single served motion bundle:
 *   mw-motion.js  =  gsap.min.js  +  ScrollTrigger.min.js  +  mw-motion-kit.js
 *
 * GSAP + ScrollTrigger are pinned, self-hosted (no cdnjs). Order matters: gsap
 * core first (defines window.gsap), then ScrollTrigger (attaches window.ScrollTrigger
 * and auto-registers against gsap), then the kit (registers the plugin + the
 * data-attribute motion engine). Concatenation is safe because each part is an
 * IIFE / UMD that only touches window.
 *
 * Usage:  node build-mw-motion.mjs   (run from this folder)
 * This folder is the tracked source (resources/local-libs/gsap). The package's
 * main build (build.mjs, via the `copy` entry {target:'gsap'} in config.js)
 * copies this whole folder into resources/dist/gsap and then into
 * public/vendor/microweber-packages/frontend-assets-libs/gsap on deploy, so the
 * rebuilt mw-motion.js ships without any extra step. Re-run this only after
 * editing mw-motion-kit.js or re-vendoring the GSAP files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const GSAP_VERSION = '3.13.0';
const parts = ['gsap.min.js', 'ScrollTrigger.min.js', 'mw-motion-kit.js'];

const banner =
  `/*! Microweber motion bundle — self-hosted GSAP ${GSAP_VERSION} + ScrollTrigger + mw-motion-kit.\n` +
  `   Generated by build-mw-motion.mjs. Do NOT edit mw-motion.js by hand — edit\n` +
  `   mw-motion-kit.js (or re-vendor the GSAP files) and re-run the build. */\n`;

const body = parts
  .map((f) => `/* ---- ${f} ---- */\n` + readFileSync(join(here, f), 'utf8').trimEnd() + '\n')
  .join('\n');

writeFileSync(join(here, 'mw-motion.js'), banner + body);
console.log('Wrote mw-motion.js (' + parts.join(' + ') + ')');
